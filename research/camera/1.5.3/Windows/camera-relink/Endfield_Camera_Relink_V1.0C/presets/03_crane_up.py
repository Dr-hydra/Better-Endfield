# 匀速升降: 相机垂直起落, 视线始终咬住角色, 速度全程恒定。
#
# 参数只有两个(外加通用的"运镜时间"):
#   h0 起始高度 / h1 结束高度(相对角色头部中心, +Z 向上)。
#   h0 < 0 是低位仰拍(显得角色高大), h1 > 0 是高位俯拍(交代位置关系)。
#   方位角与半径固定在 10° / 2.0m —— 镜头只在竖直方向动, 不掺入横移与环绕。
#
# 关键帧为什么可以只有 2 个: 竖直直线路径 + LINEAR 插值 = 精确匀速, 两端关键帧足够。


def build(ef, params):
    h0 = ef.param("h0", -0.5)
    h1 = ef.param("h1", 1.8)
    ef.crane_linear(0.0, 1.0, h0, h1, theta=10.0, radius=2.0, aim_height=0.0)
    ef.finish()
