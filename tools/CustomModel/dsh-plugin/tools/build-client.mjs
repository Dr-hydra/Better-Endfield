#!/usr/bin/env node
/**
 * Assemble `lib/client.js` from the browser source and the vendored decoder.
 *
 * The harness serves exactly one browser artifact per plugin and loads it as a
 * lazy CommonJS module, so the two sources are concatenated into one factory
 * body instead of shipped as separate files the loader would have to resolve.
 * No bundler, no transpiler: both inputs are plain JS, and the only edit is
 * removing the module `export` syntax that does not exist inside a factory.
 *
 * Usage: node tools/build-client.mjs [--check]
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = fileURLToPath(new URL('..', import.meta.url))
const decoderPath = `${root}lib/vendor/bcn.js`
const sourcePath = `${root}src/client/index.js`
const outputPath = `${root}lib/client.js`
const PACKAGE_ID = 'dsh-bem-creator'

function stripDecoderExports(source) {
  const index = source.lastIndexOf('export {')
  if (index < 0) throw new Error('vendor/bcn.js: no trailing export block to strip')
  // Everything from the last `export {` to EOF must be that one block plus the
  // sourcemap comment; anything else means the vendored file changed shape.
  const tail = source.slice(index)
  if (/^(?!export \{)[\s\S]*?\nfunction /m.test(tail)) {
    throw new Error('vendor/bcn.js: trailing export block is followed by more code')
  }
  return source.slice(0, index).trimEnd()
}

function stripClientExports(source) {
  const stripped = source
    .replace(/^export\s+const\s+/m, 'const ')
    .replace(/^export\s+function\s+/m, 'function ')
  if (/^export\s/m.test(stripped)) throw new Error('src/client/index.js: unexpected export left in the factory body')
  return stripped
}

const decoder = stripDecoderExports(readFileSync(decoderPath, 'utf8'))
const client = stripClientExports(readFileSync(sourcePath, 'utf8'))

const output = `/* eslint-disable */
// Generated by tools/build-client.mjs — do not edit.
// Sources: lib/vendor/bcn.js (BCn decoders) + src/client/index.js (preview tab).
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_ID)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${decoder}

${client}

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  }
});
`

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8')
  if (current !== output) {
    console.error('lib/client.js is stale; run node tools/build-client.mjs')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  // A stray backtick in a shader comment ends the template literal early and
  // still produces a file, so parse it before writing: the browser would only
  // report this as an empty preview tab.
  try {
    new vm.Script(output, { filename: 'lib/client.js' })
  } catch (error) {
    console.error(`lib/client.js would not parse: ${error.message}`)
    process.exit(1)
  }
  writeFileSync(outputPath, output)
  console.log(`wrote lib/client.js (${(statSync(outputPath).size / 1024).toFixed(1)} KB)`)
}
