# EFPRESET: {"name": "环绕", "desc": "绕着中心方块(角色头部)水平匀速环绕, 视线始终咬住中心",
#            "seconds": 8.0,
#            "params": [{"key": "radius", "label": "环绕半径(m)", "default": 1.8},
#                       {"key": "turn", "label": "环绕角度(度)", "default": 180.0}]}
# 环绕: 最普通的那种 —— 相机在**水平面**上绕中心匀速转, 高度与视线落点都锁在中心,
# 没有任何多余的变化(不升降、不偏摆、不带荷兰角)。
#
# 参数只有两个(外加通用的"运镜时间"):
#   radius 环绕半径 / turn 环绕角度。起手方位角固定为 -turn/2, 于是环绕在正前方左右对称。
#
# 关键帧为什么是这个数量: 匀速靠 LINEAR 插值保证(线速度精确恒定), 所以关键帧只需满足
# **三个几何精度判据**(由宿主自动求解, 见 ef.orbit_linear):
#   · 弦偏差 ≤ 1cm      —— 折线离真圆弧多远(本例 0.6mm)
#   · 折角   ≤ 3°       —— 相邻线段的方向变化, 也就是"转弯处会不会一顿"(这是上一版
#                          16 个关键帧时每 12° 拐一下、被看出来"不匀"的根因)
#   · 瞄准偏差 ≤ 0.5°   —— 视线偏离中心方块的角度(本例 0°)
# 默认参数下 180°/1.8m 得 62 个关键帧 —— 比早期自适应贝塞尔加密的 294 个少 4.7 倍,
# 而且线速度与转向都严格匀速。想要更少可以放松折角(见 ef.orbit_linear 的 kink_deg)。


def build(ef, params):
    radius = ef.param("radius", 1.8)
    turn = ef.param("turn", 180.0)
    # 归一化时间 0→1; 实际秒数由"运镜时间"参数决定(关键帧等比缩放)
    ef.orbit_linear(0.0, 1.0, theta0=-turn * 0.5, theta1=turn * 0.5,
                    radius=radius, height=0.0, aim_height=0.0)
    ef.finish()
