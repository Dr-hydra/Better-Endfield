"""Emit the compiled-in revision -> game baseline tables for both GUIs.

The Windows GUI is C# and the Android module is C++, so the same batch table has
to exist twice. Generating both from `config/game-baseline-map.json` keeps them
from drifting; `--check` fails when either generated file is stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config" / "game-baseline-map.json"
CSHARP = ROOT / "ui" / "BetterEndfieldNext.UI" / "Services" / "BemBaselineTable.Generated.cs"
CPP = ROOT / "native" / "modules" / "custom_model" / "bem_baseline_table.generated.h"

BANNER = "Generated by scripts/GenerateBemBaselineTable.py from config/game-baseline-map.json.\nEdit the JSON instead; this file is overwritten."


def load():
    data = json.loads(SOURCE.read_text(encoding="utf-8-sig"))
    rows = []
    for batch in data.get("batches", []):
        rows.append((str(batch["revision"]), str(batch["windows-x64"]),
                     str(batch["android-arm64"]), int(batch["hotfix"])))
    return rows


def csharp(rows):
    lines = [
        "// <auto-generated>",
        *(f"// {line}" for line in BANNER.splitlines()),
        "// </auto-generated>",
        "#nullable enable",
        "namespace BetterEndfieldNext.UI.Services;",
        "",
        "internal sealed record BemBaselineBatch(string Revision, string Windows, string Android, int Hotfix);",
        "",
        "internal static class BemBaselineTable",
        "{",
        "    private static readonly BemBaselineBatch[] Batches =",
        "    {",
    ]
    lines += [f'        new("{revision}", "{windows}", "{android}", {hotfix}),' for revision, windows, android, hotfix in rows]
    lines += [
        "    };",
        "",
        "    public static IReadOnlyList<BemBaselineBatch> All => Batches;",
        "",
        "    /// <summary>Exact revision match; a miss means the table does not know this batch.</summary>",
        "    public static BemBaselineBatch? Match(string revision)",
        "    {",
        "        foreach (var batch in Batches)",
        '            if (batch.Revision == revision) return batch;',
        "        return null;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def cpp(rows):
    lines = [
        "#pragma once",
        "// <auto-generated>",
        *(f"// {line}" for line in BANNER.splitlines()),
        "// </auto-generated>",
        "#include <cstddef>",
        "",
        "namespace BetterEndfieldNext::CustomModel {",
        "",
        "struct BaselineBatch {",
        "    const char* revision;",
        "    const char* windows;",
        "    const char* android;",
        "    int hotfix;",
        "};",
        "",
        "inline constexpr BaselineBatch kBaselineBatches[] = {",
    ]
    lines += [f'    {{"{revision}", "{windows}", "{android}", {hotfix}}},' for revision, windows, android, hotfix in rows]
    lines += [
        "};",
        "inline constexpr size_t kBaselineBatchCount =",
        "    sizeof(kBaselineBatches) / sizeof(kBaselineBatches[0]);",
        "",
        "}  // namespace BetterEndfieldNext::CustomModel",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = parser.parse_args()
    rows = load()
    outputs = {CSHARP: csharp(rows), CPP: cpp(rows)}
    stale = [path for path, text in outputs.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({len(rows)} batches)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
