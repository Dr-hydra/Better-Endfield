# EFPRESET: {"name": "推拉", "desc": "匀速推近或拉远(半径由大到小/由小到大)", "seconds": 6.0,
#            "params": [{"key": "r0", "label": "起始半径(m)", "default": 3.0},
#                       {"key": "r1", "label": "结束半径(m)", "default": 0.9}]}
# 匀速推拉: 相机沿一条直线朝角色靠近(或远离), 视线咬住角色, 速度全程恒定。
#
# 参数只有两个(外加通用的"运镜时间"):
#   r0 起始半径 / r1 结束半径。方位角固定在 30°(前右 3/4 机位)。
#   r1 < r0 = 推近; r1 > r0 = 拉远; 相等则相机不动(等于一个定点)。
#
# 关键帧为什么可以只有 2 个: 路径本身就是直线, 匀速直线运动用 LINEAR 插值时,
# 两个端点的关键帧就**精确**表达了整段(中间任何位置都不需要插关键帧)。


def build(ef, params):
    r0 = ef.param("r0", 3.0)
    r1 = ef.param("r1", 0.9)
    ef.dolly_linear(0.0, 1.0, r0, r1, theta=30.0, height=0.0, aim_height=0.0)
    ef.finish()
